import {test, expect, devices} from '@playwright/test';
test("US-11", async ({page}) => {
  await page.addInitScript((role) => localStorage.setItem('role', role), "ROLE-02");
  await page.goto("/ParkingEventList");
  await expect(page).toHaveURL(new RegExp("/ParkingEventList(?:[/?#]|$)"));
  await expect(page.getByTestId("parking-event-list.session-id").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-list.type").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-list.occurred-at").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-list.zone-id").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-list.message").first()).toBeVisible();
  await page.getByTestId("parking-event-list.row").first().click();
  await expect(page).toHaveURL(new RegExp("/ParkingEventDetail(?:[/?#]|$)"));
  await expect(page.getByTestId("parking-event-detail.session-id").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-detail.type").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-detail.occurred-at").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-detail.zone-id").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-detail.message").first()).toBeVisible();
  await page.goto("/ParkingEventList");
  await page.getByTestId("parking-event-list.row").first().click();
  await expect(page).toHaveURL(new RegExp("/ParkingEventDetail(?:[/?#]|$)"));
  await expect(page.getByTestId("parking-event-detail.session-id").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-detail.type").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-detail.occurred-at").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-detail.zone-id").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-detail.message").first()).toBeVisible();
  await page.goto("/ParkingEventList");
  await page.getByTestId("parking-event-list.row").first().click();
  await expect(page).toHaveURL(new RegExp("/ParkingEventDetail(?:[/?#]|$)"));
  await expect(page.getByTestId("parking-event-detail.session-id").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-detail.type").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-detail.occurred-at").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-detail.zone-id").first()).toBeVisible();
  await expect(page.getByTestId("parking-event-detail.message").first()).toBeVisible();
  await page.goto("/AdminDashboard");
  await expect(page).toHaveURL(new RegExp("/AdminDashboard(?:[/?#]|$)"));
  await expect(page.getByTestId("admin-dashboard.total-vehicles").first()).toBeVisible();
  await expect(page.getByTestId("admin-dashboard.total-zones").first()).toBeVisible();
  await expect(page.getByTestId("admin-dashboard.total-events").first()).toBeVisible();
});
