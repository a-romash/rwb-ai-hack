/**
 * Подсказка по полноте требований: какие аспекты уже упомянуты в тексте.
 * Это эвристика по ключевым словам, а не проверка. Настоящий разбор делает этап бизнес-анализа.
 */
export interface Aspect {
  key: string;
  label: string;
  tip: string;
  present: boolean;
}

const ASPECTS: readonly {key: string; label: string; tip: string; pattern: RegExp}[] = [
  {
    key: 'goal',
    label: 'Цель и проблема',
    tip: 'Какую проблему решаем и как поймём, что решили.',
    pattern: /(цел[ьи]|задач|проблем|чтобы|зачем|ценност|снизить|сократить|увеличить)/iu,
  },
  {
    key: 'users',
    label: 'Пользователи и роли',
    tip: 'Кто работает с системой: сотрудник, руководитель, администратор.',
    pattern: /(пользовател|сотрудник|водител|менеджер|администратор|оператор|диспетчер|клиент|роль|роли|аналитик)/iu,
  },
  {
    key: 'scenarios',
    label: 'Сценарии',
    tip: 'Что пользователь делает шаг за шагом и что видит в ответ.',
    pattern: /(сценари|когда|если|после|сначала|процесс|шаг|должн[аоы]? (?:определять|показывать|хранить|отправлять|создавать))/iu,
  },
  {
    key: 'data',
    label: 'Данные и интеграции',
    tip: 'Откуда берутся данные, с какими сервисами нужна связь.',
    pattern: /(данн|интеграц|api|сервис|импорт|источник|файл|координат|геоданн|справочник|база)/iu,
  },
  {
    key: 'limits',
    label: 'Ограничения',
    tip: 'Скорость, безопасность, персональные данные, платформы, сроки.',
    pattern: /(огранич|быстр|безопасн|доступн|производительн|нагрузк|персональн|152-фз|android|ios|офлайн|не требуется|не нужно)/iu,
  },
  {
    key: 'acceptance',
    label: 'Критерии приёмки',
    tip: 'Как проверить результат: демо-сценарий, метрики, ожидаемый итог.',
    pattern: /(критери|приёмк|приемк|демонстрац|ожидаем|результат|метрик|kpi|проверк)/iu,
  },
];

export function analyzeRequirements(text: string): Aspect[] {
  return ASPECTS.map(({key, label, tip, pattern}) => ({key, label, tip, present: pattern.test(text)}));
}
